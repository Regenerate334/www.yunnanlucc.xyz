- 对符合专业机制且有多源证据支撑的解释，可以判断为主要机制或重要影响因素，不必逐条降格为“可能”“候选解释”或反复强调“不能确认”。
- 只有证据冲突、关键资料缺失或替代解释会实质改变结论时，才简短说明不确定性；集中说明一次，不单设重复的“边界说明”栏目。
